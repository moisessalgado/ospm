"""Generate candidate tree-planting-slot points along a município's sidewalks (v0).

Model (v0, pilot):
  - OSM has essentially no real sidewalk geometry here (confirmed: only 63
    footway=sidewalk ways in the whole clip). So slots are generated by
    offsetting each street's centerline by a class-dependent distance that
    approximates where the sidewalk planting strip sits.
  - `sidewalk=left/right/both/no` decides which side(s) to generate when
    present; absence of the tag is treated as "both sides, unmapped" rather
    than "no sidewalk" (OSM undercoverage, not a claim about reality).
  - Points are sampled along each offset line at a fixed spacing, then any
    point falling inside an intersection buffer is dropped (too close to a
    corner/driveway to be a safe planting slot).
  - Center-median (canteiro central) slots are NOT generated in this pass —
    dual-carriageway detection needs a follow-up pass; flagged as a gap.
"""

from __future__ import annotations

import sys
from pathlib import Path

import geopandas as gpd
import numpy as np
import pandas as pd
from shapely.geometry import LineString, Point

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common.municipios import get_municipio, municipio_arg_parser  # noqa: E402

SPACING_M = 8.0  # default spacing between planting slots along a sidewalk
INTERSECTION_BUFFER_M = 6.0  # exclude slots within this radius of a street junction

# Approx. half-ROW + sidewalk-strip offset from the way centerline, per class.
# Coarse defaults — refine later with lanes=/width= where tagged.
OFFSET_BY_CLASS = {
    "living_street": 4.0,
    "residential": 5.0,
    "unclassified": 5.0,
    "service": 4.0,
    "tertiary": 6.0,
    "tertiary_link": 6.0,
    "secondary": 7.5,
    "secondary_link": 7.5,
    "primary": 9.0,
    "primary_link": 9.0,
}

EXCLUDED_CLASSES = {
    "motorway", "motorway_link", "trunk", "trunk_link", "construction", "proposed",
    "track", "path", "steps", "cycleway", "footway", "elevator", "raceway",
    "services", "rest_area", "corridor", "pedestrian", "busway",
}

SIDEWALK_NORMALIZE = {
    "r": "right", "rught": "right", "right;both": "both", "both;left": "both",
    "n": "no", "yes": "both", "separate": "both",
}


def normalize_sidewalk(value) -> str | None:
    if pd.isna(value):
        return None
    value = str(value).strip().lower()
    return SIDEWALK_NORMALIZE.get(value, value)


def sides_for(sidewalk_norm: str | None) -> list[str]:
    if pd.isna(sidewalk_norm):
        return ["left", "right"]
    if sidewalk_norm == "no":
        return []
    if sidewalk_norm == "left":
        return ["left"]
    if sidewalk_norm == "right":
        return ["right"]
    # both / unmapped (None) -> assume both sides
    return ["left", "right"]


def find_intersection_points(gdf: gpd.GeoDataFrame) -> gpd.GeoSeries:
    """Endpoints shared by 3+ way-endpoints are treated as junctions/corners."""
    endpoints = []
    for geom in gdf.geometry:
        coords = list(geom.coords)
        endpoints.append((round(coords[0][0], 1), round(coords[0][1], 1)))
        endpoints.append((round(coords[-1][0], 1), round(coords[-1][1], 1)))
    counts = pd.Series(endpoints).value_counts()
    junctions = counts[counts >= 3].index.tolist()
    return gpd.GeoSeries([Point(xy) for xy in junctions], crs=gdf.crs)


def sample_points(line, spacing: float) -> list[Point]:
    if line.geom_type == "MultiLineString":
        # offset_curve occasionally yields a MultiLineString on tight/self-
        # intersecting geometry; take the longest part as a reasonable proxy.
        line = max(line.geoms, key=lambda g: g.length)
    if not isinstance(line, LineString):
        return []
    length = line.length
    if length < spacing:
        return []
    n = int(length // spacing)
    if n <= 0:
        return []
    distances = np.linspace(spacing / 2, n * spacing, n)
    return [line.interpolate(d) for d in distances]


def main() -> None:
    args = municipio_arg_parser(__doc__).parse_args()
    municipio = get_municipio(args.municipio)
    data_dir = Path(__file__).resolve().parent.parent / "data" / municipio.slug
    out_dir = Path(__file__).resolve().parent.parent / "output" / municipio.slug
    out_dir.mkdir(parents=True, exist_ok=True)
    target_crs = municipio.epsg

    ways = gpd.read_file(data_dir / "highways_clipped.gpkg", layer="highways")
    ways = ways[~ways["highway"].isin(EXCLUDED_CLASSES)].copy()
    ways = ways.explode(index_parts=False).reset_index(drop=True)
    ways = ways[ways.geometry.geom_type == "LineString"]
    ways = ways[ways.geometry.length > 1.0]
    ways["sidewalk_norm"] = ways["sidewalk"].apply(normalize_sidewalk)

    print(f"Vias elegíveis para geração de vagas: {len(ways)}")

    junctions = find_intersection_points(ways)
    junction_buffers = junctions.buffer(INTERSECTION_BUFFER_M)
    junction_union = junction_buffers.union_all() if len(junction_buffers) else None
    print(f"Interseções detectadas (nós com 3+ ligações): {len(junctions)}")

    records = []
    for _, row in ways.iterrows():
        offset = OFFSET_BY_CLASS.get(row["highway"], 5.0)
        sides = sides_for(row["sidewalk_norm"])
        for side in sides:
            sign = 1 if side == "left" else -1
            try:
                offset_line = row.geometry.offset_curve(sign * offset)
            except Exception:
                continue
            if offset_line.is_empty:
                continue
            pts = sample_points(offset_line, SPACING_M)
            for pt in pts:
                records.append(
                    {
                        "osm_id": row["osm_id"],
                        "street_name": row["name"],
                        "highway_class": row["highway"],
                        "side": side,
                        "sidewalk_tag_source": "assumed_both" if pd.isna(row["sidewalk_norm"]) else "mapped",
                        "offset_m": offset,
                        "geometry": pt,
                    }
                )

    points = gpd.GeoDataFrame(records, geometry="geometry", crs=target_crs)
    print(f"Pontos candidatos antes do filtro de interseção: {len(points)}")

    if junction_union is not None:
        keep_mask = ~points.geometry.within(junction_union)
        points = points[keep_mask].copy()
    print(f"Pontos candidatos após excluir proximidade de esquinas: {len(points)}")

    out_gpkg = out_dir / "vagas_plantio_v0.gpkg"
    points.to_file(out_gpkg, layer="vagas_plantio", driver="GPKG")

    points_wgs84 = points.to_crs("EPSG:4326")
    out_geojson = out_dir / "vagas_plantio_v0.geojson"
    points_wgs84.to_file(out_geojson, driver="GeoJSON")

    print(f"\nSalvo -> {out_gpkg}")
    print(f"Salvo -> {out_geojson}")

    print("\n--- Resumo por classe de via ---")
    print(points.groupby("highway_class").size().sort_values(ascending=False))
    print("\n--- Origem da decisão de lado ---")
    print(points["sidewalk_tag_source"].value_counts())
    km_total = ways.geometry.length.sum() / 1000
    print(f"\nExtensão elegível total: {km_total:.1f} km")
    print(f"Total de vagas candidatas: {len(points)} (~{len(points)/km_total:.1f} vagas/km de via elegível)")


if __name__ == "__main__":
    main()
